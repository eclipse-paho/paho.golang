// TestSwitchImplementations creates a basicfile queue, adds an entry, and creates a new file queue in the same
// directory ensuring that it can read the old data, and data written by the new implementation. Also confirms that
// basicfile will return an error if the selected folder contains files generated by the new implementation.
func TestSwitchImplementations(t *testing.T) {
	dir := t.TempDir()
	q, err := New(dir, "q-", "que")
	if err != nil {
		t.Fatal(err)
	}
	if err := q.Enqueue(strings.NewReader("legacy")); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil || len(entries) != 1 {
		t.Fatalf("legacy files: %v, %v", entries, err)
	}
	// The opt-out must keep the original short numeric filename format.
	name := strings.TrimSuffix(strings.TrimPrefix(entries[0].Name(), "q-"), ".que")
	if _, err := strconv.ParseUint(name, 10, 32); err != nil {
		t.Fatalf("unexpected legacy filename %q: %v", entries[0].Name(), err)
	}
	q, err = New(dir, "q-", ".que")
	if err != nil {
		t.Fatalf("reopening legacy data: %v", err)
	}
	entry, err := q.Peek()
	if err != nil {
		t.Fatal(err)
	}
	if err := entry.Leave(); err != nil {
		t.Fatal(err)
	}

	// Stop using the old instance before opening the same namespace with file.
	upgraded, err := sequencefile.New(dir, "q-", ".que")
	if err != nil {
		t.Fatal(err)
	}
	if err := upgraded.Enqueue(strings.NewReader("sequenced")); err != nil {
		t.Fatal(err)
	}
	if _, err := New(dir, "q-", ".que"); err == nil {
		t.Fatal("basicfile accepted mixed legacy and sequence data")
	}
	for _, want := range []string{"legacy", "sequenced"} {
		entry, err := upgraded.Peek()
		if err != nil {
			t.Fatal(err)
		}
		r, err := entry.Reader()
		if err != nil {
			t.Fatal(err)
		}
		got, err := io.ReadAll(r)
		if err := entry.Remove(); err != nil {
			t.Fatal(err)
		}
		if err != nil || string(got) != want {
			t.Fatalf("read %q, %v; want %q", got, err, want)
		}
	}
	q, err = New(dir, "q-", ".que")
	if err != nil {
		t.Fatalf("reopening drained namespace: %v", err)
	}
	if _, err := q.Peek(); !errors.Is(err, queue.ErrEmpty) {
		t.Fatalf("drained queue Peek: %v", err)
	}
}

// Set known, well-separated timestamps so the legacy ordering test does not
// depend on the host's clock or filesystem timestamp resolution.
func setModTimes(t *testing.T, q *Queue, order []string) {
	t.Helper()
	entries, err := os.ReadDir(q.path)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		path := filepath.Join(q.path, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		found := false
		for i, want := range order {
			if string(data) == want {
				stamp := time.Unix(1_600_000_000+int64(i)*10, 0)
				if err := os.Chtimes(path, stamp, stamp); err != nil {
					t.Fatal(err)
				}
				found = true
				break
			}
		}
		if !found {
			t.Fatalf("unexpected queue contents in %q: %q", entry.Name(), data)
		}
	}
}
